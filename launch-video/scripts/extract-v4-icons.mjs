// Extracts the Phosphor icons the v4 film uses into src/v4/icons.generated.ts (no runtime icon dependency).
//   node scripts/extract-v4-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../node_modules/@phosphor-icons/core/assets/", import.meta.url);
const NAMES = [
  "envelope", "envelope-simple", "chat-circle-dots", "chat-circle", "check-square", "file-text", "users-three", "calendar-blank",
  "currency-circle-dollar", "note-pencil", "kanban", "plant", "timer", "lightning", "sun", "tray", "clipboard-text",
  "magnifying-glass", "play", "check", "check-circle", "pause", "sparkle", "star", "receipt", "target", "credit-card",
  "clock", "paper-plane-tilt", "folder", "chart-line", "bell", "fire", "speaker-high",
];
const WEIGHTS = { duotone: "-duotone", fill: "-fill", regular: "", bold: "-bold" };
const out = {};
for (const name of NAMES) {
  out[name] = {};
  for (const [w, suf] of Object.entries(WEIGHTS)) {
    const svg = readFileSync(new URL(`${w}/${name}${suf}.svg`, ROOT), "utf8");
    out[name][w] = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon)\s([^>]*?)\/?>/g)]
      .map((m) => ({ tag: m[1], attrs: Object.fromEntries([...m[2].matchAll(/([\w-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]])) }))
      .filter((e) => !(e.tag === "rect" && e.attrs.width === "256"));
  }
}
writeFileSync(new URL("../src/v4/icons.generated.ts", import.meta.url),
  `// GENERATED by scripts/extract-v4-icons.mjs from @phosphor-icons/core (MIT). Do not edit.\n// viewBox 0 0 256 256.\nexport const ICONS = ${JSON.stringify(out)} as const;\nexport type IconName = keyof typeof ICONS;\nexport type IconWeight = "duotone" | "fill" | "regular" | "bold";\n`);
console.log("icons", NAMES.length);
