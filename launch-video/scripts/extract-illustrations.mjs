// Converts the illustration SVGs in art-src/ (IMG-01.svg, IMG-06a.svg, …) into
// src/brand/illustrations.generated.ts, so the film can build each drawing up
// path by path (and give its layers parallax) instead of showing a flat image.
//
//   node scripts/extract-illustrations.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const DIR = new URL("../art-src/", import.meta.url);
const out = {};
for (const file of readdirSync(DIR).filter((f) => /^IMG-.*\.svg$/.test(f)).sort()) {
  const svg = readFileSync(new URL(file, DIR), "utf8");
  const [, w, h] = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  // Only drawn paths: skip the clipPath's rect in <defs>.
  const paths = [...svg.matchAll(/<path d="([^"]+)" fill="([^"]+)"\/>/g)].map((m) => ({ d: m[1], fill: m[2] }));
  out[file.replace(".svg", "")] = { w: Number(w), h: Number(h), paths };
}
const body = `// GENERATED by scripts/extract-illustrations.mjs from art-src/*.svg. Do not edit.
export const ART: Record<string, { w: number; h: number; paths: { d: string; fill: string }[] }> = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../src/brand/illustrations.generated.ts", import.meta.url), body);
console.log("wrote", Object.keys(out).map((k) => `${k} (${out[k].paths.length} paths)`).join(", "));
